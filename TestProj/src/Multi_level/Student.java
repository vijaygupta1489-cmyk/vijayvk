package Multi_level;

public class Student extends Dept {

	protected int Studid;
	protected String Studname;
	
	public int getStudid() 
	{
		return Studid;
	}
	public void setStudid(int studid) {
		Studid = studid;
	}
	public String getStudname() {
		return Studname;
	}
	public void setStudname(String studname) {
		Studname = studname;
	}
	
	
	
}
